import type { ReactNode } from 'react';

/**
 * 词条里的**行内强调**。
 *
 * ---------------------------------------------------------------------------
 * 为什么需要它（这是一个真实存在了一段时间的界面缺陷）
 * ---------------------------------------------------------------------------
 * 词条里用 `**这样**` 表示强调，中英两份都是这么写的 —— 所以它是一个
 * **有意的约定**。但界面从来没有把它渲染出来：全站唯一把 Markdown 变成
 * 粗体的入口是 `<Markdown>`，而它只用于**用户提交的正文**
 * （`body` / `descriptionMd`），从来不用于 `t(...)`。
 *
 * 结果是用户直接看到一对星号：
 *
 *     这里记录的是**频道**，不是「现在谁在播」……
 *
 * 2026-09-13 在真浏览器里读 `/live` 的 `innerText` 时才发现的。
 * 当时全站有 **15 条**这样的词条，其中 13 条早于那次改动 —— 也就是说
 * 它已经这样很久了，而**没有任何自动检查会发现它**（词条 key 存在、
 * 两种语言对齐、字体覆盖都过）。
 *
 * ---------------------------------------------------------------------------
 * 为什么是一个函数而不是一个组件
 * ---------------------------------------------------------------------------
 * 因为用法是 `{em(t('...'))}` 而不是 `<Em text={...}/>` ——
 * 调用点有十几处，其中一半在 `<Field hint={...}>` 和
 * `<p className="...">{...}</p>` 这种"位置上放的就是一段文本"的地方。
 * 一个返回 `ReactNode` 的函数在两处都能直接用，组件则要各包一层。
 *
 * ---------------------------------------------------------------------------
 * ⚠️ 刻意只支持 `**粗体**` 这一种标记
 * ---------------------------------------------------------------------------
 * 不做完整的 Markdown：**用户内容**才需要完整的 Markdown 管线
 * （而且那条管线必须经过 `rehype-sanitize`）。而这里是**我们自己写的词条**，
 * 不需要标题、链接、列表 —— 支持得越多，就越容易有人往词条里写链接，
 * 然后我们不得不在一个本该只有粗体的地方补一套 sanitize。
 *
 * ⚠️ 这个文件里有**两个**出口，用法不同、不要混用：
 *   · `em(text)`   → `ReactNode`，"能放节点"的地方（`{em(t('…'))}` / `<Field hint>`）
 *   · `emText(text)` → `string`，"只能是字符串"的地方（`title=` / `aria-label=`）
 *   分工与判据写在 `emText` 自己的注释里。
 */
export function em(text: string): ReactNode {
  if (!text.includes('**')) return text;

  const parts = text.split('**');

  /*
   * ⚠️ 落单的 `**`（奇数个）**整条原样返回**，不做半渲染。
   *
   *    半渲染的结果是"这一句的前半段是粗体、后半段带着两个星号"，
   *    比完全不渲染更难看，而且看起来像渲染坏了 —— 而真正的原因是
   *    词条里少写了一个星号。原样返回至少是一个**明显**的错误，
   *    一眼能看出"这里有个星号不该在"。
   *
   *    （`'a**b'.split('**')` → `['a','b']`，长度 2 = 偶数 = 不配对。）
   */
  if (parts.length % 2 === 0) return text;

  return parts.map((part, index) =>
    // 奇数下标 = 被 `**` 夹住的那一段
    index % 2 === 1 ? <strong key={String(index)}>{part}</strong> : part,
  );
}

/**
 * `em()` 的**纯文本版**：同一个强调约定，**剥掉**标记而不是渲染成节点。
 *
 * ---------------------------------------------------------------------------
 * 为什么还需要它（2026-09-14；`docs/pending.md §5.62` 的那一半）
 * ---------------------------------------------------------------------------
 * 因为有几处**只能放字符串**，那里没有"粗体"这回事：
 *
 *   · `title={…}` —— HTML 的 tooltip 就是一段纯文本，**没有粗体 tooltip**。
 *     把 `t('authoring.directHint')` 原样放进去，浏览器气泡里就是
 *     「这次改动**直接生效**（不进审核队列）」——一对字面星号。
 *   · `aria-label={…}` / 存进 state 的 string / 写进 `<option>` 的值 —— 同理。
 *
 * ⚠️ 这些地方**不能**改用 `em()`：
 *   它返回的是 `ReactNode`（字符串或元素数组），而 `title` 的形参类型是 `string`。
 *   类型检查会当场报错；硬塞进去（`as unknown as string` 之类）的话，React 把那个
 *   数组按 `'' + value` 转成字符串，页面上会出现 `a,b` 这种带逗号的怪东西。
 *   ⇒ **字符串上下文用 `emText()`，节点上下文用 `em()`。**
 *
 * ---------------------------------------------------------------------------
 * ⚠️ 策略必须与 `em()` **逐字一致**（尤其是落单的那一半）
 * ---------------------------------------------------------------------------
 * `em()` 对**落单**的 `**`（奇数个）**整条原样返回**，理由是"让写坏的词条继续
 * 看得见"（那段注释在 `em()` 上面）。`emText()` 沿用同一条：
 * `parts.length % 2 === 0` ⇒ 原样返回，**不**图省事把所有 `**` 都 `replace` 掉。
 * 否则同一个坏词条在两种上下文里会给出两种结果，而"看不见的那种"恰好就是
 * 悄悄擦掉标记的这一种 —— 那正是 `em()` 拒绝做的事。
 *
 * ⇒ 两者的一致性由**探针**守着（`apps/web/scripts/authoringNotice.ts`：
 *   "`em(s)` 渲染出来的纯文本必须等于 `emText(s)`"，含落单 / 成对 / 无标记三种输入）。
 *   改这里的策略时那条会红 —— 别只改这里。
 *
 * ⚠️ 成对时"剥掉标记"等于 `parts.join('')`（`split` 已经把 `**` 当分隔符吃掉了），
 *    **不是**只留偶数下标那几段 —— 被 `**` 夹住的那一段是**正文**，必须留下。
 */
export function emText(text: string): string {
  if (!text.includes('**')) return text;

  const parts = text.split('**');

  // 落单的 `**`：与 `em()` 同样**整条原样返回**（看得见的错，而不是被擦掉）
  if (parts.length % 2 === 0) return text;

  return parts.join('');
}
