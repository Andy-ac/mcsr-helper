/**
 * 实时分享 · 介绍页 `/shares`（**公开**）。
 *
 * ===========================================================================
 * ⚠️★ 这个文件里**没有界面**，只有取数
 * ===========================================================================
 * 界面（标题 / 导语 / 两块入口卡片 / 条数那一行）**全在** `components/ShareCard.tsx`
 * 的 `ShareIntroView` 里。理由与 `components/` 里那个贡献者面板的同一处拆分是同一个：
 * 这个页面**自己取数**，而 `renderToStaticMarkup` **不跑 effect**（也不点击、不发请求）
 * ⇒ 整页在渲染自检里**永远停在"加载中"**，写在它里面的任何一块都**断言不到**
 * ——那是一条不可能红的守卫（`docs/pending.md §5.63`）。
 * ⇒ 这里只有三件事：`useAuth()`、一次 `fetchShareSummary`（**游客不发**）、
 *    `<ShareIntroView authed={…} summary={…} />`（Task 8 渲染的正是那个纯视图）。
 *    属性少传、传错都会被 **typecheck** 抓住（`src/**` 在 tsconfig 的 include 里）。
 *
 * ===========================================================================
 * ⚠️★ 游客一个请求都不发（spec §7.2）
 * ===========================================================================
 * `GET /api/shares/summary` 要求登录（§5.2）⇒ **先看 `useAuth()`，登录了才请求**，
 * 不是"发了再吃 401"：那会在服务端留下一条"有人在试着读"的噪音（每一次游客访问
 * 都来一条，而这台服务器只有 1 核），而游客看到的是"先加载、再变成登录后可见"
 * 那一次闪烁。游客手上 `summary` 永远是 `null` ⇒ 界面渲染「登录后可见」，
 * **不是**一个 `0 条在展示`（那会让他以为这里现在没人分享，而事实是内容不给他看）。
 *
 * ===========================================================================
 * ⚠️★ `auth.loading` 那一小段时间里**不按游客渲染**
 * ===========================================================================
 * `auth.loading` 为真时"到底登录没登录"还不知道（`AuthProvider` 正在跑
 * `GET /api/auth/me`）。这段时间按游客渲染的话，**已经登录的人会先看到一句
 * 「登录后可见」**，半秒后才跳成条数。两处现成的口径都指向同一个答案：
 *   · `ShareIntroView` 里那一支的注释就是为这件事写的 ——「登录了但还没取到：
 *     说"加载中"，**不要**说"登录后可见"（他自己就是登录用户）」；
 *   · 本仓对这个形状（侧栏底部"未登录 / 用户名"）已经写下了结论：「加载中时刻意
 *     什么都不显示，不要显示"未登录"……而且会让已经登录的用户以为掉线了」
 *     （`components/Layout.tsx` 那段注释）。
 * 这里没有第三格可以渲染成"空"，所以退一步：`authed` 传"是登录这一支"，
 * 于是那半秒里条数那一行说的是 `common.loading`（「加载中」）—— 与全站其它页面
 * 在 `auth.loading` 期间说的是**同一句话**。
 * ⚠️ 代价记在明面上：游客会在开头那半秒看到「加载中」再变成「登录后可见」。
 *    它比"对一个登录用户说登录后可见"轻，而且它**不是** §7.2 要治的那次闪烁 ——
 *    那一次是"游客多发了一个注定 401 的请求"造成的，而这里**一个请求都没发**。
 *
 * ===========================================================================
 * ⚠️ 不自动刷新（spec §7.6）
 * ===========================================================================
 * 这里**刻意没有任何定时器、也没有 `visibilitychange`**：本页是静态介绍 +
 * 一个**附注性质**的条数，没有"实时"的要求。§7.6 专门写了这一句，防的正是
 * "同属一个栏目，于是顺手把看板那套 20 秒轮询也抄过来"（那一套只属于 `ShareBoard`）。
 *
 * ===========================================================================
 * ⚠️ 为什么这一页是**公开**的（§1.1）
 * ===========================================================================
 * 本栏目是全站第一个"内容游客看不到"的地方，而那一条例外**只针对两个看板**：
 * 介绍页本身照样公开 —— 游客在这里读到的是"这个栏目在干什么"（§7.2 的导语），
 * 而不是一堵墙。所以这里没有登录门，也不许因为"反正内容要登录"就把它挡住。
 *
 * ⚠️ 取数失败**没有专门的界面**：`summary` 留在 `null`，登录用户看到的是「加载中」
 *    （`ShareIntroViewProps` 里**没有**出错那一格，契约在 Task 5 就冻结了，
 *    而 Task 8 正是照着那一格渲染的 ⇒ 不在这一轮改它）。
 *    这是一个**记下来的取舍**：条数是附注性的，而这一页在公开路径上 ——
 *    为它在整页再引一个错误块，比它本身重。再试一次 = 刷新页面。
 */
import type { ShareSummary } from '@mcsr/shared';
import { useEffect, useState } from 'react';
import { ShareIntroView } from '@/components/ShareCard';
import { fetchShareSummary } from '@/lib/api';
import { useAuth } from '@/lib/auth';

export function ShareIntro() {
  const auth = useAuth();

  /** `null` = 还没取到（或游客，压根不会去取）—— 与 `ShareIntroViewProps.summary` 同一件事。 */
  const [summary, setSummary] = useState<ShareSummary | null>(null);

  /*
   * ★ 发不发请求的**唯一**依据是"谁登录着"（`userId`），不是 `auth.loading`：
   *   · 游客 —— 含 `auth.loading` 那一段（那时 `user` 还是 `null`）⇒ 不发；
   *   · 登录用户 ⇒ 发一次。 ⚠️ 依赖取的是 **id** 而不是 `auth.user` 那个对象：
   *     对象在 `refresh()` 重取同一个人的资料后会换一个新的，取对象会让这一页
   *     白发一次请求（与 `routes/CalendarDetail.tsx` 的 `[id, auth.loading, auth.user?.id]`
   *     同一条做法）。
   *
   * ⚠️ 为什么不用 `lib/useAsync.ts`：它的 loader **一定会跑**（那是"游客不发"的反面），
   *    而"条件发请求"这件事只能由调用方自己判。它的另一条特性（依赖一变就回到
   *    "加载中"）这里也不需要 —— 这一页本来就只有一次取数。
   */
  const userId = auth.user?.id ?? null;

  useEffect(() => {
    /*
     * ★★ 游客：**一个请求都不发**（§7.2），而且手上不许留着任何条数。
     * 后一半说的是"刚退出登录"那一支 —— 这条分支也是**登出**时唯一会跑到的地方。
     * 上一个人的条数虽然被 `authed` 挡在画面上（视图那一支渲染的是「登录后可见」），
     * 但那个值本来就不该继续待在组件里。
     * ⚠️ `summary` 已经是 `null` 时 React 直接跳过重渲染，所以这一句不会让这一页
     *    每次挂载多跑一轮渲染。
     */
    if (userId === null) {
      setSummary(null);
      return;
    }

    const controller = new AbortController();
    fetchShareSummary(controller.signal)
      .then((data) => setSummary(data))
      .catch((error: unknown) => {
        // abort 是我方主动取消（卸载 / 换了人），不当作失败来看
        if (error instanceof DOMException && error.name === 'AbortError') return;
        // 失败：条数留 `null`（文件头写了为什么这里没有错误界面）
        setSummary(null);
      });
    return () => controller.abort();
  }, [userId]);

  return (
    <ShareIntroView
      /*
       * ⚠️★ `auth.loading` 也走"登录了这一支"（推导写在文件头）：那半秒里传 `false`
       *    会对一个**已经登录的人**说「登录后可见」。
       */
      authed={auth.loading || auth.user !== null}
      summary={summary}
    />
  );
}
