/**
 * 实时分享 · 剩余时间的算法 —— **纯函数，单独一个文件**。
 *
 * ===========================================================================
 * ⚠️ 它必须单独存在，因为它是**唯一**能被渲染自检断言的那一半
 * ===========================================================================
 * 这一栏最核心的性质是"**到点那一秒从画面上消失**"（spec §7.6）。它由两部分拼成：
 *   · 一个每秒推进的本地时钟（`nowMs`）—— 住在页面里（Task 7 的 `ShareBoard`）；
 *   · "还剩几分钟 / 到点了没有"这个**判断** —— 就是这里。
 *
 * 如果这个判断写进组件的 effect 里，它就永远只有人眼能验：`renderToStaticMarkup`
 * 既不跑 effect 也不推进时间（本仓已经有两次这样的教训，见 Task 5 的 Step 3b）。
 * 抽成纯函数之后，`apps/web/scripts/sharerender.tsx` 可以**喂一个固定的时刻**
 * 进去，把每一档（还剩 N 天 / N 小时 / N 分钟 / 不到 1 分钟 / 已经到点）分别断言出来。
 *
 * ===========================================================================
 * ★ 为什么必须有 `serverOffset`（这不是顺手的）
 * ===========================================================================
 * 剩余时间**必须按服务端时间算**（spec §5.1：读接口里的 `serverNow` 是必需的）：
 * 一台快 3 分钟的机器会**提前**把还没到点的行从画面上抹掉，慢 3 分钟的机器会让
 * 过期的行一直挂着。两种都是"界面在撒谎"，而且都不会有任何报错。
 * ⇒ 做法是：拿到响应时用 `serverOffset(serverNow, 本地此刻)` 算一个**偏移量**，
 *   之后所有倒计时都用它把本地时钟折算成服务端时刻。
 *
 * ⚠️★ 偏移量**只能算一次**（一次响应一次）—— 每秒重算的话，
 *    `nowMs + offset` 恒等于那个 `serverNow`，剩余时间**每秒都是同一个数**，
 *    倒计时根本不会动，"到点即消失"就退化成了"下一次 20 秒轮询时才消失"。
 *    冻住它的地方在 `components/ShareCard.tsx` 的 `useServerOffset`（那里有完整代数）。
 *
 * ===========================================================================
 * 这三个函数的断言在哪
 * ===========================================================================
 * `apps/web` **没有测试运行器**（2026-09-15 现读 `package.json`：只有
 * `dev` / `build` / `check:*` / `preview` / `typecheck`，**没有 `test`**）。
 * ⇒ 按本仓既有做法，它们由 `apps/web/scripts/sharerender.tsx`（`check:share`）断言，
 *   而不是为此新引入一个测试框架（那会让这条不变量多一份会漂移的第二实现）。
 */

/** `t()` 的最小形状 —— 只取这三个函数需要的那一档（与 `lib/seedErrors.ts` 同形）。 */
export type Translate = (key: string, options?: Record<string, unknown>) => string;

/**
 * 服务端时刻与本地时刻之差：`serverNow - localNow`。
 *
 * ⚠️ 它的**唯一**用途是把本地时钟折算成服务端时钟，所以两个参数必须是
 *    **同一个瞬间**的两次读数（拿到响应的那一刻）。隔几秒再算，算出来的是
 *    "服务端时钟 + 网络延迟"，倒计时会自己抖。
 */
export function serverOffset(serverNow: number, localNow: number): number {
  return serverNow - localNow;
}

/**
 * 还剩多少毫秒。`<= 0` = **已经到点**，调用方要把那一行从画面上去掉。
 *
 * ⚠️ 判据写成 `remainingMs(...) > 0` 而不是 `expiresAt > Date.now()`：
 *    后者在渲染路径上直接读时钟，而"到点即消失"正是要能被渲染自检断言的那一件事。
 */
export function remainingMs(expiresAt: number, localNow: number, offset: number): number {
  return expiresAt - (localNow + offset);
}

/**
 * 「还剩 N 天 / N 小时 / N 分钟」/「不到 1 分钟」—— 到点时是**空串**。
 *
 * ⚠️ 空串是**刻意的**：调用方拿到空串就该把那一行去掉（§7.4 的"到点那一秒从画面上
 *    消失"由本地计时负责）。所以每一档都不会印出"还剩 0 …"。
 * ⚠️ 向上取整（`Math.ceil`）：剩 11 分 01 秒时说「还剩 12 分钟」是**保守**的说法，
 *    而向下取整会在还剩 59 秒时说「还剩 0 分钟」——那正是这一档不想要的观感。
 *
 * ===========================================================================
 * ★ 四档（2026-09-16 从两档扩出来的，因为种子改成了按天）
 * ===========================================================================
 * 种子的展示窗口最长 30 天，而房间最长 20 分钟 ⇒ 只有"分钟"一档的话，
 * 一条挂了 29 天的种子会印出「还剩 41760 分钟」。⇒ 单位跟着**剩余量**走：
 *
 * | 剩余 | 印出来的 |
 * |---|---|
 * | `<= 0` | 空串（调用方据此摘掉那一行） |
 * | `< 1 分钟` | 不到 1 分钟 |
 * | `1–59 分钟` | 还剩 N 分钟 |
 * | `1–23 小时` | 还剩 N 小时 |
 * | 其余 | 还剩 N 天 |
 *
 * ⚠️★ 换档的判据用的是**取整之后**的那个数（`minutes < 60` / `hours < 24`），
 *    不是原始毫秒。两者只差一个边界，而那个边界恰好是**最难看**的那一格：
 *    按毫秒判的话，剩 59 分 30 秒会印出「还剩 60 分钟」、剩 23 小时 59 分
 *    会印出「还剩 24 小时」—— 两个都像 bug。按取整后的数判就没有这种画面
 *    （代价是 59 分 01 秒 起就说「1 小时」、23 小时 00 分 01 秒 起就说「1 天」，
 *    那两句都是**保守**的说法，不是错话），而且"同一个单位下印出来的数总是
 *    剩余量的向上取整"这条性质仍然成立。
 * ⚠️ 天那一档**没有**再往上的单位（上界就是 30 天），所以它不需要边界判断。
 */
export function remainText(ms: number, t: Translate): string {
  if (ms <= 0) return '';
  if (ms < 60_000) return t('shares.remainUnderOne');

  const minutes = Math.ceil(ms / 60_000);
  if (minutes < 60) return t('shares.remainMinutes', { n: minutes });

  const hours = Math.ceil(ms / 3_600_000);
  if (hours < 24) return t('shares.remainHours', { n: hours });

  return t('shares.remainDays', { n: Math.ceil(ms / 86_400_000) });
}
