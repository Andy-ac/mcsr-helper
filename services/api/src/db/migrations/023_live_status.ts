/**
 * 023：`live_channels` 的三列 —— 这一页**第一次**会知道"在不在播 / 多少人看"。
 *
 * | 列 | 语义 |
 * |---|---|
 * | `is_live`         | `1` 在播 / `0` 不在播 / **`NULL` = 从没查过、或这一次查不到** |
 * | `viewer_count`    | 人数；**`NULL` = 上游没给**（不是 0） |
 * | `live_checked_at` | 这一次查的时刻（**Unix 秒**）；`NULL` = 从没查过 |
 *
 * ===========================================================================
 * 一、★ 为什么 `NULL` 与 `0` 必须分开（这条迁移存在的理由）
 * ===========================================================================
 * `0` 与"读不到"是两句**不同**的话，而它们在界面上必须能分辨：
 *   · `is_live = 0` —— 我们**问过上游**，它说这个人现在没在播；
 *   · `is_live IS NULL` —— 我们**没问过**（这一列刚加、那个平台我们还不查、
 *     或者这一轮整条上游失败）。把它读成"不在播"，用户就会以为我们替他确认过了 ——
 *     而那是我们没有做过的事。
 * ⇒ 三列**全部可空、都没有 DEFAULT**：SQLite 的 `ADD COLUMN` 是 O(1) 的元数据操作，
 *    既有的 184 行（2026-09-18 生产快照实测：twitch 183 / youtube 1 / bilibili 0）
 *    拿到的就是 `NULL` ⇒ **"从没查过"**，这正是它们真实的状态。
 *
 * ⚠️ 同理 `viewer_count` **不许用 0 表示"不知道"**（本仓"绝不为缺失值填 0"那条）：
 *    界面上"0 人观看"与"这一格什么都没显示"是两件事，而 0 是一个**它自己会说的话**
 *    —— 上游真的会回 0（实测：Twitch 的在播流里有 `viewer_count=0` 的条目）。
 *    所以 0 只能有一个来源：上游真的这么说了。
 *
 * ===========================================================================
 * 二、`CHECK (is_live IN (0, 1))` —— 一条**能红**的守卫
 * ===========================================================================
 * 判据是"这一列只允许三个值：`NULL` / `0` / `1`"。
 * 少写这条 CHECK 的后果是**静默**的：写进去一个 `2`（比如某个适配层把 `live_status`
 * 原样塞进来 —— bilibili 那个字段实测取值是 0/1/2，其中 **2 也是"不在播"**），
 * 界面按"`=== 1` 才算在播"读它，谁都不会报错，而这一行永远显示"不在播"。
 * ⚠️ 本机实测（`.cache/videos-live-round/probe-023-sqlite.mjs`，在**生产副本**上跑的）：
 *    SQLite 收得下 `ADD COLUMN … CHECK (…)`，且 `is_live = 3` 当场被拒
 *    （`CHECK constraint failed: is_live IN (0, 1)`），`1` 与 `NULL` 都写得进去。
 *    ⇒ 这条约束不是装饰，它真的会红。
 *
 * ===========================================================================
 * 三、⚠️ 为什么不建索引（量过才敢不建）
 * ===========================================================================
 * 新的公开列表排序是"在播的在前、在播内部按人数降序、其余保持原样"
 * （见 `services/api/src/live.ts` 的 `LIVE_ORDER_BY`）。它**不是**一个纯列序，
 * 要用得上索引就得建表达式索引，而代价是每次写都维护它。
 * 实测（同一份生产副本，脚本同上）：
 *   · 这张表一共 **184 行**，已有 `idx_live_listing (status, sort_order)`；
 *   · 那条新排序语句 `EXPLAIN QUERY PLAN` 走的就是 `idx_live_listing`，
 *     排序落到 `USE TEMP B-TREE FOR ORDER BY`；
 *   · 整条语句**跑 20 次合计 8.9 ms**（≈ 0.45 ms/次；本探针脚本的 ④，
 *     `.cache/videos-live-round/probe-023-sqlite.out.txt`）。
 *     ⚠️ 同一份快照上，迁移**演练**脚本另量到 **12.1 ms**（`rehearse-023.out.txt`）——
 *     两个数都带着出处，而原先 `live.ts` 里那个"10.7"**没有任何留档**（终审 M5 订正）。
 *     两处 `ms` 都是"20 次合计"，数量级一致 ⇒ 结论（不建索引）不受这两个数之差影响。
 * ⇒ 184 行的临时排序比维护一个表达式索引便宜得多，所以这一条**只加列、不加索引**。
 *    真到了几万行再说 —— 那时该改的是分页方式，不是顺手补一个索引。
 *
 * ⚠️ 与 011 / 015 / 021 / 022 同一个形状：纯 `ALTER TABLE ADD COLUMN`，**不重建表**
 *    ⇒ 不需要 `PRAGMA foreign_keys`，**留在事务里**（不加 noTransaction），失败即整条回滚。
 * ⚠️ 不登记 = 不跑，症状是"代码看着对、库里没有那三列"（020/021 两轮都踩过）。
 *    演练读数（生产副本）：`.cache/videos-live-round/rehearse-023.out.txt`。
 */
