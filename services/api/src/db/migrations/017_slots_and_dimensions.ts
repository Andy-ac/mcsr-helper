/**
 * 017：多段时间 + 四个维度 + 系列颜色（2026-09-13，用户要求 ④⑤⑥）。
 *
 * ===========================================================================
 * 一、`calendar_events.time_slots` —— 一场赛事可以有**多段不连续**的时间
 * ===========================================================================
 * 用户原话：「把『开始时间』『结束时间』改成允许输入多段不连续的时间
 * （如……新增『添加』按钮，允许再填一组），同时时区放在最上面，只填一次即可」。
 *
 * ★ **为什么既有那 6 个时间列一个都不删**（这是本次改动最重要的一个决定）
 *   它们退化成这条事件的**包络**（最早那段的开始 / 最晚那段的结束），
 *   写入时由多段算出来。这样做的好处是：**排序、索引、系列计数、
 *   ICS 的"还没结束"筛选全都不用改** —— 它们读的一直是那一对列。
 *
 *   ⚠️ 代价是"同一件事存在两处"（多段 + 包络）。这是**刻意的**，而且与
 *      `starts_at_utc` 由"本地时间 + 时区"算出来是同一个形状：
 *      **包络是派生的，不是第二个真相** —— 它只在写入时算一次，之后不再变。
 *   ⚠️ 谁改多段，**必须同时重算包络**（`toColumns` / `payloadToColumns` 是唯一的
 *      写入点；漏了会让新加的那一段落在"已结束"的判定之外，而两边都不报错）。
 *
 * `time_slots` 的形状（JSON 数组，按开始时间升序）：
 *   [{ "startsAtLocal": "2026-09-12T00:00", "endsAtLocal": "2026-09-14T00:00",
 *      "startsAtUtc": 1789…, "endsAtUtc": 1789… }, …]
 *   ⚠️⚠️ **键名必须与 `packages/shared/src/calendar.ts` 的 `interface EventSlot` 逐字一致。**
 *      这段注释的初版写的是 `startLocal` / `endLocal` / `startUtc` / `endUtc`（少一个 `s`、
 *      少一个 `At`），而**读写两侧没有任何校验**（`slotsOfRow` 是一次 `as EventSlot[]` 断言）
 *      ⇒ 照注释写出来的数据会让每一段的日期变成 `undefined`，
 *      表现是"日历上一条日期条都不画"，**而不会报任何错**。
 *      写数据脚本的人（子代理）按**代码**写对了，是这段注释错了 —— 已改。
 *   · 时区**不在每一段里** —— 用户要求"只填一次"，所以整条事件共用
 *     `starts_at_tz` 那一列（`ends_at_tz` 与它相同，保留只为兼容既有读路径）。
 *   · UTC 在**写入时**算好（与既有三列设计同一条理由：时区数据库会更新，
 *     现算会让历史数据跟着变）。
 *
 * ===========================================================================
 * 二、`calendar_events.access` —— 参赛门槛（新维度）
 * ===========================================================================
 * 用户要求新增「参赛门槛」：选拔制 / 邀请制 / 无门槛。
 * ⚠️ **可空**，理由与 level/scope 相同：排位节点那类活动没有门槛可言，
 *    必填会逼人瞎选，而瞎填的数据比空值更难用（空值至少是诚实的）。
 * ⚠️ **不加 CHECK**（与 011 的 level/scope 同一个理由）：SQLite 改不了 CHECK，
 *    而这一维的取值一定会变（用户这一轮就刚把"专业程度"从四档收敛到两档）。
 *
 * ===========================================================================
 * 三、`calendar_events.scope_detail` —— 「参与范围」的明细
 * ===========================================================================
 * 用户要求：不是全球时允许再选具体信息（例如"大洲：亚洲&大洋洲"），
 * 而且主页筛选选「大洲」之后也能选具体大洲。
 *
 * ⚠️ 用户先选了"复用 tags"，后来（我摊开后果之后）改成**独立字段**：
 *    复用会让主页的「标签」筛选同时列出「赛事」和「亚洲」两个正交维度。
 * ⚠️ 存 JSON 数组（代码字符串，如 `["ASIA","OCEANIA"]`）：大洲与国家共用这一列。
 *
 * ===========================================================================
 * 四、`calendar_series.color` —— 系列颜色
 * ===========================================================================
 * 用户要求「每个系列用一个颜色标注，允许 owner 修改每个系列的颜色，
 * 无系列的为白色（注意描边）」。颜色**只用于**：日历上那条日期横线 +
 * 「系列活动」左侧的小点（用户原话）。
 * ⚠️ 存**调色板的键**（`red` / `teal` …）而不是色值：色值由我们按主题推导，
 *    这样两个主题下都看得清，而 owner 也选不出"和背景一样的颜色"。
 * ⚠️ 可空 = 没上色（界面走"无系列"那一档：白色 + 描边）。
 *
 * ===========================================================================
 * 五、删掉 015 的 `schedule_text`
 * ===========================================================================
 * 它的职责被 `time_slots` 完全取代（用户原话：「你可以直接删掉」）。
 * ⚠️ 那些值是**我从同一份 Liquipedia 抽取里写的**，同一份数据现在写进 `time_slots`
 *    （脚本 `.cache/apply-phaseB.mjs` 用的是同一张周末表）—— 所以删掉它不丢信息。
 * ⚠️ `DROP COLUMN` 要 SQLite ≥ 3.35；本机与线上都是 3.53（部署前实测过）。
 */
export const m017SlotsAndDimensions = `
  -- 1) 多段时间（包络仍在既有那 6 列里，写入时算）
  ALTER TABLE calendar_events ADD COLUMN time_slots TEXT;

  -- 2) 参赛门槛：选拔制 / 邀请制 / 无门槛。可空、不加 CHECK（见文件头）
  ALTER TABLE calendar_events ADD COLUMN access TEXT;

  -- 3) 参与范围的明细：大洲 / 国家的代码数组
  ALTER TABLE calendar_events ADD COLUMN scope_detail TEXT;

  -- 4) 系列颜色：存调色板的键，不存色值
  ALTER TABLE calendar_series ADD COLUMN color TEXT;

  -- 5) 015 的「具体时间」由 time_slots 取代
  ALTER TABLE calendar_events DROP COLUMN schedule_text;
`;
