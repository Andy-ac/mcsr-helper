/**
 * 018：内容贡献者（2026-09-14，用户要求）。
 *
 * 用户原话：「对于资源库，在后台记录贡献者（不直接展示在资源库中），贡献者可以
 * 不经过审核直接修改/下架其拥有的资源（不实际删除），管理者可以在资源库中看到
 * 贡献者，并且能在每个资源里面随意修改（添加/删除）贡献者。资源可以没有贡献者。
 * 贡献者不单独作为一个身份组。这套逻辑之后在其他板块还要用到。」
 *
 * 表结构、字段含义与"为什么是两段式而不是 resource_contributors"的完整说明
 * 在 `packages/shared/src/contributors.ts` 的文件头 —— **先去读那一段**，
 * 这里只写**这张表自己的**三个决定。
 *
 * ===========================================================================
 * 一、⚠️ 没有外键指向被贡献的那一行（这是本表最重要的一个取舍）
 * ===========================================================================
 * `user_id` 有外键，而被贡献的实体是 `(entity_type, entity_id)` 两段 ——
 * **SQLite 没法给这种形状建外键**：一张表的外键只能指向一张表，而这里指的是
 * "好几张表里的那一张"。
 *
 * ⇒ 代价落在一个**不会报错**的地方：删掉一条内容**不会**自动清掉它的贡献者行。
 *   每一条硬删除的路径都必须自己调 `deleteContributors(entityType, entityId)`，
 *   否则留下的是**指向不存在内容的孤儿行** —— 它不违反任何约束、不产生任何日志，
 *   只会在"这个人被列为某条已删内容的贡献者"这种地方安静地误导人。
 *   ⚠️ 所以它有一条**测试**守着（`contributors.test.ts`：删掉资源之后那几行必须为 0），
 *      而不是靠"下次记得写那行代码"。
 *
 * ===========================================================================
 * 二、两个外键的删除行为**不一样**，而且各自表达一件不同的事
 * ===========================================================================
 *   · `user_id ... ON DELETE CASCADE` —— 账号注销后，那一行**没有意义**：
 *     "某人是一条内容的贡献者"这句话里，某人已经不存在了。留着它只会让
 *     名单上出现一个永远无法解析的 id。
 *   · `added_by ... ON DELETE SET NULL` —— "谁把他加进去的"是**历史**，
 *     而历史不该因为那个人注销就跟着消失（否则名单上会凭空少一个人，
 *     看起来像"从未被加过"）。与 `audit_log` 刻意不给 actor_id 建外键
 *     是同一条理由：账号注销恰恰是最需要留痕的时候。
 *     ⇒ 所以 `Contributor.addedBy` 是可空的，界面要能显示"未知"。
 *
 * ===========================================================================
 * 三、索引只建一个，而且顺序是 `(user_id, entity_type)`
 * ===========================================================================
 * 主键 `(entity_type, entity_id, user_id)` 已经覆盖了"读一条内容的名单"
 * 这个**最高频**的查询（列表页/详情页的管理界面都用它）。
 * 另一个方向是反的：`contributorEntityIds(userId, entityType)` 回答
 * "**这个人**在资源库里能直编哪几条" —— 列表页要**批量**判断，
 * 不能写成 N 次查询，所以它需要 `(user_id, entity_type)` 这个前缀。
 * 两列的顺序是刻意的：先按人收窄（一个人的行很少），再按类型收窄。
 *
 * ⚠️ 它与 013/017 同一个性质：纯 `CREATE TABLE` / `CREATE INDEX`，
 *    **不重建任何表** ⇒ **留在事务里**（不加 noTransaction）——
 *    失败能整体回滚。`noTransaction` 存在的唯一理由是"迁移里要用
 *    `PRAGMA foreign_keys`"（见 migrate.ts 的注释），这里用不上。
 */
export const m018ContentContributors = `
  CREATE TABLE content_contributors (
    -- 被贡献的东西住在哪张表：目前只有 'resource'，加板块时加一个值
    entity_type TEXT    NOT NULL,
    -- 那一行的 id。⚠️ 没有外键（见文件头一）
    entity_id   TEXT    NOT NULL,
    -- 谁能直接改它。账号注销 → 这一行跟着消失（见文件头二）
    user_id     TEXT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- 谁把他加进去的。那个人注销 → 置空，但**这一行要留着**（见文件头二）
    added_by    TEXT             REFERENCES users (id) ON DELETE SET NULL,
    created_at  INTEGER NOT NULL,

    -- 同一个人在同一条内容上只能有一行 —— 名单是集合，不是流水账。
    -- 用它来做幂等：整份替换时重复的 id 交给数据库挡住，而不是靠调用方去重
    PRIMARY KEY (entity_type, entity_id, user_id)
  );

  -- "这个人能直编哪几条" —— 列表页**批量**判断用（见文件头三）
  CREATE INDEX idx_content_contributors_user ON content_contributors (user_id, entity_type);
`;
