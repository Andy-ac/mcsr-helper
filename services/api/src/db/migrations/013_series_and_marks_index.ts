/**
 * 013：系列活动（③）+ 收藏数索引（⑤）。
 *
 *   1. `resource_marks` 上的部分索引 —— 服务"这一页里每条内容被多少人收藏"（⑤）。
 *   2. `calendar_series` 表 + `calendar_events.series_id` 可空外键 —— 把同一活动的
 *      不同赛季/届次归到一起（③ 裁决 = (A) 实体）。
 *
 * ===========================================================================
 * ⚠️ 这条迁移**不需要** noTransaction —— 它全是非重建操作
 * ===========================================================================
 * 三件事（`CREATE INDEX` / `CREATE TABLE` / `ADD COLUMN`）在 SQLite 里都**不重建表**，
 * 所以：
 *   · 不需要 `PRAGMA foreign_keys = OFF`（那个 PRAGMA 在事务里无效，
 *     只有"重建表"才需要它 —— 见 007/008/012 的文件头）；
 *   · 因此**必须留在事务里**：失败时整体回滚。
 *
 * ⚠️ `migrate.ts:56-63` 专门警告过这件事：**别看到"改表结构"就条件反射加 noTransaction**，
 *    那会白白丢掉回滚。这条迁移正是那个警告针对的情形。
 *
 * ⚠️ `ADD COLUMN ... REFERENCES tbl(col)` 在 `foreign_keys = ON` 下是合法的
 *    （SQLite 允许新增带外键的列，只要默认值是 NULL），本仓已实测（spec F25）。
 *    新列对**所有已有行**填 NULL —— 那正是想要的语义："这些事件还不属于任何系列"。
 *
 * ===========================================================================
 * ⚠️⚠️ 写这条迁移时**不要**在模板字符串里用反引号
 * ===========================================================================
 * 一个反引号就会提前闭合模板串，报错指向 SQL 的中间某行，和真正的原因毫无关系
 * （012 在这上面踩过 4 处）。SQL 注释里用「」或单引号括标识符。
 *
 * ===========================================================================
 * 部署前
 * ===========================================================================
 * 即使这条能回滚，也仍然要在**生产库副本**上先跑一遍（`.cache/rehearse-migration.mjs` 的写法），
 * 并确认：`calendar_series` 建出来了、`calendar_events` 多了一列 `series_id`、
 * 两条索引都在、以及 `_migrations` 里出现 013。
 */

export const m013SeriesAndMarksIndex = `
  -- -------------------------------------------------------------------------
  -- 1) ⑤ 收藏数：列表页要按「这一页的 id」一次数出每条的收藏人数
  -- -------------------------------------------------------------------------
  /*
   * ⚠️ 部分索引（WHERE favorite = 1），不是全表索引：
   *    这张表里一个人只要写过**备注或评分**就会有一行，而收藏数的查询只关心
   *    favorite = 1 的那些。带上这个条件，索引的体积跟着"真的被收藏的条数"走，
   *    而不是跟着"被标记过的条数"走。
   */
  CREATE INDEX idx_marks_favorite ON resource_marks (resource_id) WHERE favorite = 1;

  -- -------------------------------------------------------------------------
  -- 2) ③ 系列活动：系列是**实体**（同一个名字只能有一个系列）
  -- -------------------------------------------------------------------------
  /*
   * ⚠️ name 上的 COLLATE NOCASE UNIQUE 是**这条设计的关键**：
   *    「MCSR Ranked」与「mcsr ranked」会撞上同一条 UNIQUE，于是大小写变体
   *    天然是同一个系列，而**显示名保留用户第一次输入的那个**。
   *    没有它就得在应用层折叠大小写 —— 那要么把显示名改丑，要么再加一列 key。
   *
   * ⚠️ 但 NOCASE **不折叠空白**：「MCSR Ranked」与「MCSR  Ranked」（两个空格）
   *    在库眼里是两个名字。所以写入前必须过 shared 的 normalizeSeriesName()。
   */
  CREATE TABLE calendar_series (
    id         TEXT    PRIMARY KEY,
    name       TEXT    NOT NULL COLLATE NOCASE UNIQUE,
    created_by TEXT,
    created_at INTEGER NOT NULL
  );

  /*
   * 事件只**指向**系列，不冗余存名字 —— 两份名字必然漂移（系列一改名，
   * 老事件上留着旧名字，而两边都不会报错，只是显示不一致）。
   * 名字在读路径上用 LEFT JOIN 取（见 calendar/events.ts 的 listEvents）。
   *
   * ⚠️ 可空：绝大多数赛事不属于任何系列，这不是"还没填"。
   */
  ALTER TABLE calendar_events ADD COLUMN series_id TEXT REFERENCES calendar_series (id);

  /*
   * 按系列筛事件时用得上。和 011 里那两条一样**只建在已发布的行上** ——
   * 日历的查询绝大多数带 status 条件，而待审/已下架的场次不该混进系列的计数里。
   */
  CREATE INDEX idx_calendar_series ON calendar_events (series_id) WHERE status = 'published';
`;
