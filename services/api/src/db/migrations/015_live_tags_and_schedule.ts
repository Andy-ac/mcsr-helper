/**
 * 015：两处「允许填写多个值」的字段（2026-09-13，用户要求）。
 *
 * ---------------------------------------------------------------------------
 * 1. `live_channels.tags` —— 直播频道可以带多个标签
 * ---------------------------------------------------------------------------
 * 用户原话：「将『频道标识』改成『标签』，可输入多个标签，暂时不需要做标签筛选功能」。
 *
 * ⚠️ **`handle`（频道标识）没有被删掉，也不该删**：公开名单上每一条的"去原频道看"
 *    链接、以及 YouTube 的频道级嵌入，都是**按平台 + handle 拼出来的**
 *    （`liveChannelUrl` / `liveEmbedDecision`）。把 handle 换成标签，那些链接就没有
 *    来源了 —— 表现是"卡片还在，点进去是空的"。
 *    ⇒ 所以这里是**新增一列**，而不是替换：标签是给人看的分类，handle 是链接的原料。
 *
 * ⚠️ 存 JSON 数组文本（和 `calendar_events.tags` 同一个做法），不建关联表：
 *    这一栏只用来**显示**（用户明确说暂时不做筛选），一次 JOIN 都不需要。
 *    ⚠️ 真要按标签筛选时，这个形状会成为麻烦（LIKE 的转义、误配前缀）——
 *    那时应当迁移到关联表，而不是把 LIKE 写得更复杂。
 *
 * ---------------------------------------------------------------------------
 * 2. `calendar_events.schedule_text` —— 活动可以填**离散**的多个时间段
 * ---------------------------------------------------------------------------
 * 用户原话：「活动的时间允许填入离散的时间」，随后要求按"一般为 3 个周末"去改
 * Playoffs 的具体时间。
 *
 * ⚠️ 为什么是**一列文本**而不是"多个时间段"的结构：
 *    · 现有模型是「一个开始 + 一个结束」（`starts_at_*` / `ends_at_*`），日历网格、
 *      排序、ICS 全都建在它上面。改成多区间要动网格、排序、ICS、审核快照四处，
 *      而用户明确要求"快速解决"；
 *    · 而且本仓对"按轮次拆开"的既有答案是 **一条时间片一个事件**
 *      （见 `shared/constants.ts` 里 `EVENT_STAGES` 的注释：真实数据里两种形态并存）。
 *    ⇒ 所以这一列是**给人读的具体赛程**（例如三个周末各一行），
 *      不改事件的定位语义：`starts_at_utc` 仍然是"整场赛事从哪天到哪天"。
 */
export const m015LiveTagsAndSchedule = `
  -- 标签：JSON 数组文本，例如 ["速通","Ranked"]。NULL = 没填。
  ALTER TABLE live_channels ADD COLUMN tags TEXT;

  -- 具体赛程：自由文本，允许换行（离散的多个时间段就一行一个）。NULL = 没填。
  ALTER TABLE calendar_events ADD COLUMN schedule_text TEXT;
`;
