/**
 * ② 高分对局**一批**渲染几场：首批这么多，之后每点一次「加载更多」再追加这么多。
 *
 * ---------------------------------------------------------------------------
 * ★ 为什么是 20：用户要的是「全部展示」，但"全部"不等于"同一帧里全塞进 DOM"
 * ---------------------------------------------------------------------------
 * 2026-09-19 用户的原话是「ranked 实时信息高分对局**全部展示**」（原来取前 10）。
 * 那句话说的是"**能不能看到全部**"，不是"必须一次性渲染完"：这一页每 10 秒轮询一次
 * （`RANKED_POLL_MS.live`），每一轮都会重渲染**整张**列表，而一张卡片不是一行文字
 * —— 十几个节点，外加一个 `<details>`（里面还有点数不定的播放器门面）。
 * 上游的 `/live` **没有条数上限**，所以"全渲染"的真代价是：几百张卡片时每 10 秒
 * 按住一次主线程（"实时"从外面看就像卡住），而那个列表**没有人会滚到底**
 * （最新的对局在顶部，底部那些卡片本来就基本不会被看到）。
 * ⇒ 留一个可点的「加载更多」：想看完的人点得到，不点的人不必为它付钱。
 *
 * 20 这个数不是猜的：本仓的记录里上游一次给了 **23 场**（`docs/progress.md`：实测
 * "23 场里按平均 elo 取前 10"），常见的量级就是二三十场 ⇒ 首批 20 场让**绝大多数情况
 * 一个按钮都不用点**，同时把 DOM 的规模挡在"一次刷新几十个节点"这一档。
 *
 * ⚠️★ 它**不是**"取前 20"：这个数只决定**一次渲染几场**，不决定"谁被丢掉"——
 *    列表是**完整**的（排序后），后面的场次在「加载更多」里，界面上那句
 *    「还有 N 场」说的就是它们（`sliceLiveMatches` 的 `remaining`）。
 * ⚠️ 它替换掉了原来的 `RANKED_LIVE_TOP = 10`（连同 `topLiveMatches`）：那一个是
 *    **截断**（第 11 场开始谁也看不到），与用户这次的要求正好相反。
 *    名字从 `_TOP` 改成 `_BATCH` 是必须的 —— 沿用旧名字会让"取前 N"的旧读法在这里
 *    悄悄活下来，而那种误读的表现是"加载更多只加载了前 20 场里的一部分"。
 */
export const RANKED_LIVE_BATCH = 20;

/**
 * ③ 排行榜渲染几行 —— **150，而且这个数不是我们选的**（2026-09-19 用户裁决：显示前 150）。
 *
 * ---------------------------------------------------------------------------
 * ★★ 150 是**上游的硬上限，而且没有分页**（实测，不是"我们只取前 150"）
 * ---------------------------------------------------------------------------
 * 实测（findings §2.4，同样的调用今天又量了一遍）：`/leaderboard` 的响应体里
 * **恒为 150 条**，而 `?count=200` / `?count=1` / `?page=1&count=150` 与不带参数的那一次
 * **字节完全相同**（同为 32 830 字节，SHA-256 也相同）⇒ 那两个参数是**被忽略**的，
 * 不是"生效了但被截断"。⇒ **第 151 行拿不到**：没有 `count`、没有 `page`、
 * 文档里也没有这两个参数（文档的 `count` 1–100 属于**比赛列表**那几个端点）。
 *
 * ⚠️★ 所以这里**没有**"下一页"、没有"加载更多"：这一栏显示的就是上游那份完整榜单，
 *    一个字节都没有被我们丢掉。下一个读代码的人不必去找那个不存在的分页按钮 ——
 *    它不存在的原因写在上面这两段里，而不是"还没做"。
 * ⚠️ 它在 `select.ts` 里仍然要通过 `topEloEntries` 过一道截断（150 是最坏情况下的**上界**）：
 *    上游哪天改成给 300 条（文档与实测都没有承诺过 150 是永久的），界面不会被撑爆，
 *    而那一天要改的就是这一个数。
 * ⚠️ 它**不是** 100 了：`RANKED_ELO_TOP = 100` 是这一栏原来的口径（用户当时只要前 100），
 *    用户 2026-09-19 明确要求前 150 ⇒ 这个数跟着改，别把 100 留在注释里当"实测值"。
 */
export const RANKED_ELO_TOP = 150;

