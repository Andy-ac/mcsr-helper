/**
 * ★★ ①「状态栏」要显示的**四个组件** —— 顺序、上游的监视器 id、以及各自的词条 key。
 *
 * ===========================================================================
 * ⚠️⚠️ 这张表是**这一栏唯一一处"从网页上抄下来"的知识**（其余全是 API 给的）
 * ===========================================================================
 * 心跳响应里**没有名字**：那具身子的形状是 `heartbeatList: {"2": [...], "3": [...], …}`
 * —— 键是**光秃秃的监视器 id**（实测：恰好 `["2","3","4","5"]`）。
 * 名字（`Game Server` / `API` / `Store` / `Wiki`）只出现在**人看的那张状态页**的
 * 内联脚本里（`window.preloadData.publicGroupList[0].monitorList[].name`，
 * 按同一个 `…monitorList[].id` 配对）。
 *
 * 那条路**没有 API 可用**（2026-09-17 实测）：`/api/status-page/mcsrranked`、
 * `…/config`、`/api/status` **三个都是 403 `Invalid request`**，能读到的只有那张
 * 2 576 字节的 HTML。⇒ 两个选择，两个都有代价，我们选了前者：
 *   · **写死这四对 id→名字**（本表）：零请求、零新依赖；代价是**上游重新编号监视器时
 *     它会悄悄错位** —— 而"错位"表现为状态栏上两个组件的名字互换了，界面上**看不出**
 *     哪一个错了（两个名字都合法、两个状态都是真的）。
 *   · **服务端抓那张 HTML 解析**：名字永不过期；代价是给一个**明确是人看的页面**
 *     加一条上游依赖 —— 那个页面重新设计一次，我们就会静默地拿不到名字（而它今天
 *     已经在改造范围里了，403 的三个兄弟端点就是证据）。
 * ⇒ **这就是"唯一一处未经 API 验证的映射"**：评审与下一个人请把"名字不对"的排查起点
 *   放在这张表上，而不是去查心跳解析（那一层是实测过的）。
 *   ⚠️ 唯一能**自动**发现它错位的办法是人工对一次状态页（`pending.md` 里记着这件事）。
 *
 * ⚠️ 四个 id 的**顺序**是用户点名的那个顺序（Game Server → API → Store → Wiki）：
 *    状态页自己那一组的显示顺序是 **2, 3, 5, 4**（Wiki 在 Store 前面），而
 *    文档的散文与用户原话都是 2/3/4/5 ⇒ 界面按**用户的顺序**排，不照抄状态页的顺序。
 * ⚠️ `nameKey` 而不是名字字面量：这一栏两种语言各渲染一遍（渲染自检），
 *    名字写死在组件里就没法分开调（`timeline.ts` 那张表是同一条做法）。
 *    这四个名字是上游的**专有名词**，两种语言里今天都是同一串英文。
 * ⚠️★ 这一栏只认**表里这四个**：上游哪天加了第五个监视器，它**不会**出现在我们的状态栏上
 *    （我们按表迭代，而不是按 `heartbeatList` 的键迭代 —— 后者会让界面长度随上游变）。
 *    这是**刻意的**：用户要的就是这四个。发现上游加了东西时的正确动作是往这张表里加一行。
 */
