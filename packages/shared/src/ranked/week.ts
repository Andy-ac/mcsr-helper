/*
 * ===========================================================================
 * ⚠️★ 上游的周 id 空间**不是单调的**（2026-09-16 实测）
 * ===========================================================================
 *   · `104`（未来）→ 400 `race is not found`；
 *   · `0`        → **返回第 103 周**：它是"本周"的别名，不是一周；
 *   · `-1`       → 真的存在（43 条，endsAt 2026-04-30），**且它是唯一的负周**
 *                  （-2 / -3 / -10 都是 400）。
 * ⇒ 用户的口径：**-1 显示成「第 0 周」，1 起一一对应**。
 * ⇒ 于是翻页不是 `id ± 1`，而是一个**跨过 0** 的阶梯函数；
 *    ⛔ 两个函数都**结构上**不可能产出 0 —— 请求 0 会拿到另一周的数据，
 *    界面会闪一下然后跳到本周，而 URL 里写着 0。
 * ⚠️ 这几个判断都住在**纯函数**里（不是写在组件里）：`apps/web` 没有测试运行器，
 *    写在组件里的分支**没有任何门禁看得见**（spec §11.2 逐值钉的就是这几个数）。
 */

/**
 * 上游的周 id → 界面上那个周数。上游把"第 0 周"记成 `-1`（唯一的负周）。
 *
 * ⚠️ 否决了"照原样显示 `-1`"：界面上会印出「第 -1 周」，而 -1 只是上游的一个下标 ——
 *    读者看到的是一句没有任何含义的话。改这一条会让周赛面板第 0 周那条断言当场红
 *    （spec §11.4 mutation ②）。
 */
export function displayWeekNo(id: number): number {
  return id === -1 ? 0 : id;
}

/**
 * 上一周。`1 → -1`（跨过 0，因为 0 是"本周"的别名）；`-1` 是最早的一页。
 *
 * ⚠️ 否决了 `id - 1`：它会给出 `prevWeekId(1) === 0`，而 0 在上游是**本周的别名**
 *    ⇒ URL 里写着 0、屏幕上却是本周的数据（"闪一下然后跳回去"）。
 *    要挡住它不能靠调用方自觉，只能让这个函数**结构上**产不出 0。
 * ⚠️ 判据写成 `id <= 1` 而不是 `id === 1`：上游只承认 `-1` 与 `>= 1` 这些 id，
 *    所以这一支真正的用处是"调用方给了一个上游不存在的 id"（0、-2…）——
 *    那时回落到最早的一页（`-1`）比顺着减下去造出一个更早的 id 更安全。
 */
export function prevWeekId(id: number): number | null {
  if (id === -1) return null; // 第 0 周是最早的一页（-2 / -3 实测都是 400）
  if (id <= 1) return -1; // 第 1 周的上一页 = 第 -1 周（显示为第 0 周）；0 被跳过去
  return id - 1;
}

/**
 * 下一周。`-1 → 1`（同样跨过 0）；到最新周就没有了（调用方据此把它渲染成**不可点**而不是链接）。
 *
 * ⚠️ 否决了 `id + 1`：`nextWeekId(-1, latest) === 0`（同一类缺陷，只是发生在第 0 周那一页）。
 * ⚠️ 判断用 `id >= latestId` 而不是 `id === latestId`：最新周由**响应里的 `data.id`** 决定
 *    （spec §6.5：请求 0 会拿到 103，而我们要显示 103），传进来一个更大的 id 只会出现在
 *    "上游删了一周"这种情形里，那时也应当没有下一页，而不是拼出一个 404 的链接。
 */
export function nextWeekId(id: number, latestId: number): number | null {
  if (id >= latestId) return null;
  if (id === -1) return 1; // 同样跳过 0
  return id + 1;
}

/**
 * 某一周的路径。
 *
 * ⚠️ 本周（`/ranked/weekly`，不带 id）由调用方自己给根路径：那个地址**不带周号**，
 *    刷新时始终指向"此刻的周"。否决了"本周也拼 id"：那样页面会在打开的那一刻
 *    钉死在上游当时的 id 上，用户刷新时看到的是"上一次打开的那一周"，
 *    而标签页上的「周赛」看起来已经是最新的了。
 */
export function weekPath(id: number): string {
  return `/ranked/weekly/${String(id)}`;
}
