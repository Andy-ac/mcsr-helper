/**
 * 审核管线的通用契约 —— **服务端和前端共用**。
 *
 * ---------------------------------------------------------------------------
 * 为什么要做成通用的（而不是"先做资源库的，M4 再说"）
 * ---------------------------------------------------------------------------
 * M4 要加日历、视频、种子三类内容，它们**全都要走同一条管线**：
 * 提交 → 待审 → 发布 → 留痕。
 *
 * 如果第一版把资源库的字段（kind / url / tags）写死在审核界面里，
 * M4 加第二类内容时就只有两条路：
 *   · 复制一份界面改字段（三份几乎一样的代码，改一处漏两处）
 *   · 回头重构（那时已经有真实审核数据在跑，改动风险大得多）
 * 两条都难。所以**第一版就把它抽象出来** —— 代价是现在多写一点类型，
 * 收益是 M4 只需要注册一条新类型。
 *
 * ---------------------------------------------------------------------------
 * 抽象的形状：队列项是通用的，审核内容是各类型自己的
 * ---------------------------------------------------------------------------
 * 分成两层，因为这两件事的"通用程度"不同：
 *
 *   1. **队列项**（下面 QueueItem）—— 完全通用。
 *      审核员在列表里需要的信息，任何内容类型都一样：
 *      标题、作者、是不是对已发布内容的修改、什么时候提交的。
 *
 *   2. **审核详情**（各类型自己的 payload）—— 不通用。
 *      审核资源库要看 URL 和正文，审核种子要看种子值和结构，
 *      审核日历要看时间和地点。硬要统一成一个字段表，就会得到
 *      一堆"类型 A 用、类型 B 不用"的可空字段 —— 那比不抽象更糟。
 *
 * 所以：**列表通用，详情按类型**。前端用一个注册表把两者接起来。
 */

