/**
 * 贡献者 —— 一条内容可以有一组"能直接改它的人"。
 *
 * ===========================================================================
 * 这是什么（2026-09-14，用户要求）
 * ===========================================================================
 * 用户原话：
 *   「对于资源库，在后台记录贡献者（不直接展示在资源库中），贡献者可以不经过审核
 *     直接修改/下架其拥有的资源（不实际删除），管理者可以在资源库中看到贡献者，
 *     并且能在每个资源里面随意修改（添加/删除）贡献者。资源可以没有贡献者。
 *     贡献者不单独作为一个身份组。这套逻辑之后在其他板块还要用到。」
 *
 * 逐条对应到设计：
 *   · **后台记录**、**不直接展示** ⇒ 它是数据，不是公开字段。公开列表/详情里
 *     一个字都不出现（`ResourceListItem` 不带它），只有管理界面读得到。
 *   · **不经过审核** ⇒ 贡献者走的是那条**直编**路径（`/api/authoring/*`），
 *     与 `content.author` 用的是同一套机制，不是第二套。
 *   · **下架、不实际删除** ⇒ 只有 `published ⇄ hidden` 这一对可逆动作；
 *     `DELETE` 那条路与它无关（那仍然要 `canHardDelete` / `content.author`）。
 *   · **资源可以没有贡献者** ⇒ 它是**额外**的一组人，**不取代** `author_id`。
 *     提交者仍然是提交者；贡献者是"另外几个可以动它的人"。空集合是常态。
 *   · ★ **不单独作为一个身份组** ⇒ 它是**逐条内容的关系**，所以：
 *       - `permissions.ts` 里**没有**、也不该有 `contributor` 这个角色或能力；
 *       - 判据是数据（"你是不是这一条的贡献者"），不是矩阵里的一行。
 *     ⚠️ 这一条是本文件存在的理由之一：把它做成一个角色，就等于说"某个人的一切
 *        改动都不用审核"，而用户要的是**逐条**授权的。
 *   · **之后其他板块还要用到** ⇒ 所以下面那张表是 **(entity_type, entity_id)**
 *     两段式，而不是 `resource_contributors`。加一个板块时只加一个实体类型常量，
 *     数据层与路由都照原样复用。
 *
 * ===========================================================================
 * ⚠️ 表是通用的，所以**没有外键指向被贡献的那一行**
 * ===========================================================================
 * `content_contributors` 只有 `user_id` 指向 `users`（`ON DELETE CASCADE`：
 * 账号注销后那一行没有意义）。
 * 而被贡献的实体是 `(entity_type, entity_id)` 两段，**SQLite 没法给这种形状建外键**
 * —— 一张表外键只能指向一张表，而这里指向"好几张表里的一张"。
 *
 * ⇒ **代价必须记住**：删掉一条内容**不会**自动清掉它的贡献者行。
 *   每一条硬删除的路径都要自己清（`deleteContributors(entityType, entityId)`），
 *   否则会留下**指向不存在内容的孤儿行** —— 而它们不会报错，只会在"某人被列为
 *   某条已删内容的贡献者"这种地方安静地误导人。
 *   ⚠️ 这也是为什么它需要一条**测试**守着（删内容之后贡献者行必须为 0），
 *      而不是靠"记得写那行代码"。
 *
 * ===========================================================================
 * ⚠️ 这个文件与 Caddy 上的 `id` 形状
 * ===========================================================================
 * `user_id` / `entity_id` 都是服务端生成的 id 字符串，**客户端不能自己造**。
 * 下面那张 schema 只负责"形状对不对"，"这个人/这条内容存不存在"由路由查库。
 * 分成两层是刻意的：schema 是前后端共用的（前端要立刻能校验），
 * 而存在性只有服务端知道。
 */
import { z } from 'zod';

/**
 * 目前支持贡献者的实体类型。
 *
 * ⚠️ **加一个板块时加一个值**（同时要在服务端那边有一张能查存在性的表）。
 *    刻意做成**闭集**：开放字符串会让"打错一个字母"变成一条永远匹配不上的孤儿行，
 *    而它不会报错，只会让某个人莫名其妙地没有权限。
 */
export const CONTRIBUTOR_ENTITY_TYPES = ['resource'] as const;
export type ContributorEntityType = (typeof CONTRIBUTOR_ENTITY_TYPES)[number];

/**
 * 一条内容最多几个贡献者。
 *
 * 50 是**手数**定的：资源库现在有 6 条用户提交的内容，而这个功能是"另外几个
 * 能改它的人"，不是"按名单授权"。⚠️ 它挡的是**手滑**（前端选错、脚本循环），
 * 不是安全边界 —— 真有人要 51 个，改这个数就行。
 */
export const CONTRIBUTORS_MAX = 50;

/** 一条贡献者记录（对外形状）。 */
export interface Contributor {
  userId: string;
  /**
   * 显示名。
   *
   * ⚠️ 可空，而且**调用方不能假设它一定有**：账号注销之后 `users` 那一行没了
   *    （`ON DELETE CASCADE` 会让贡献者行一起消失），但"用户从未设过显示名"
   *    是完全正常的状态。界面上回退显示 id 或"未知用户"，**不要**留空。
   */
  displayName: string | null;
  /** 谁把他加进去的。`null` 表示那个人后来注销了（`added_by` 是 SET NULL）。 */
  addedBy: string | null;
  createdAt: number;
}

/** `GET /api/resources/:id/contributors` 的响应。 */
export interface ContributorList {
  items: Contributor[];
  total: number;
}

/**
 * 改贡献者名单的入参 —— **整份替换**，不是"加一个/删一个"。
 *
 * ⚠️ 为什么是整份替换而不是两个增量接口：管理界面本来就是"勾选一组人然后保存"，
 *    而增量接口要处理"同时加了又删了""加的人已经在里面"这些并发情况，
 *    每一条都要一个错误码。整份替换是**幂等**的：同一个请求发两次结果一样，
 *    而这是"保存按钮被点两下"最省事的答案。
 * ⚠️ 代价：两个管理员同时编辑时**后写的赢**（前一个的改动被静默覆盖）。
 *    这个规模的名单上可以接受，但它是有代价的 —— 所以界面上那张名单要**现取**，
 *    不要用打开页面时缓存的那一份。
 */
export const ContributorsInputSchema = z
  .object({
    /** 替换之后的完整名单。空数组 = 把贡献者清空（合法，而且资源可以没有贡献者）。 */
    userIds: z.array(z.string().trim().min(1)).max(CONTRIBUTORS_MAX),
  })
  .strict();

export type ContributorsInput = z.infer<typeof ContributorsInputSchema>;
